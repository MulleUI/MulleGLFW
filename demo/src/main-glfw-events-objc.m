#import "import.h"

#include <stdio.h>

/*
 * MEMO: this version uses a GLFWOSWindow, but the events are still base
 *       glfw code.
 *
 * This creates a platform window, without a graphics context. But...
 * Not useful!!
 *
 * It should still be possible to get all the platform events in a portable
 * manner, which would be a win already.
 *
 */
static void   key_callback(GLFWwindow* window, int key, int scancode, int action, int mods)
{
   printf( "key: %d\n", key);
   fflush( stdout);
}


static void   mouse_button_callback( GLFWwindow* window, int button, int action, int mods )
{
   printf( "button: %d\n", button);
   fflush( stdout);
}

static void   cursor_position_callback( GLFWwindow* window, double x, double y )
{
   printf( "cursor: %.1f %.1f\n", x, y);
   fflush( stdout);
}


static void   framebuffer_size_callback( GLFWwindow* window, int w, int h)
{
   printf( "framebuffer: %d %d\n", w, h);
   fflush( stdout);
}


int main( void)
{
   GLFWOSWindow    *gWindow;
   GLFWwindow      *window;
   UIApplication   *app;

   app = [UIApplication sharedInstance];

   @autoreleasepool
   {
      //
      // GLFWOSWindow with GLFW_NO_CONTEXT to only get events. Can this
      // work without OpenGL ? YES and NO. Linking is probably problematic
      //
      gWindow = [[[GLFWOSWindow alloc] initWithFrame:CGRectMake( 0.0, 0.0, 500.0, 500.0)
                                    titleUTF8String:"Demo"
                                          styleMask:UIWindowStyleResizable
                                      graphicsHints:GLFW_NO_CONTEXT] autorelease];
// not needed since we don't do [app runApp]
//      [app addWindow:gWindow];

      window = [gWindow os_window];
      assert( window);

      glfwSetFramebufferSizeCallback( window, framebuffer_size_callback);
      glfwSetKeyCallback( window, key_callback);
      glfwSetMouseButtonCallback( window, mouse_button_callback);
      glfwSetCursorPosCallback( window, cursor_position_callback);

      while (!glfwWindowShouldClose(window))
      {
          //glfwWaitEventsTimeout( 0.0);
          glfwWaitEvents();
      }
    }

    [app terminate];
    return( 0);
}

