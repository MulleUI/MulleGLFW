#import "import.h"


/*
 * MEMO: This version uses GLFWOSWindow, it's just the base
 *       glfw code.

 * This creates a platform window, without a graphics context. But...
 * Not useful!!
 *
 * It should still be possible to get all the platform events in a portable
 * manner, which would be a win already.
 *
 */

static void   receiveWindowEvents( GLFWOSWindow *window, UIWindowEvent *event)
{
   mulle_printf( "%@\n", [event class]);
   fflush( stdout);
}


static void   otherRetainedEventsCallback( GLFWOSWindow *window, UIEvent *event)
{
   mulle_printf( "%@\n", [event class]);
   fflush( stdout);

   [event release];
}


static void   renderFrame( GLFWOSWindow *window)
{
   struct CGBitmapSize   framebufferSize;

   framebufferSize = [window os_framebufferSize];
   glViewport( 0, 0, framebufferSize.width, framebufferSize.height);
   glClearColor( 0, 0, 0, 0);
   glClear( GL_COLOR_BUFFER_BIT);
}

//#define HINTS  GLFW_NO_CONTEXT
#define HINTS 0

int   main( int argc, char *argv[])
{
   GLFWOSWindow    *window;
   UIApplication   *app;

   app = [UIApplication sharedInstance];

   @autoreleasepool
   {
      //
      // GLFWOSWindow with GLFW_NO_CONTEXT to only get events. Can this
      // work without OpenGL ? YES and NO. Linking is probably problematic
      //
      window = [[[GLFWOSWindow alloc] initWithFrame:CGRectMake( 0.0, 0.0, 500.0, 500.0)
                                    titleUTF8String:"Demo"
                                          styleMask:UIWindowStyleResizable
                                      graphicsHints:HINTS] autorelease];
      [app addWindow:window];

      [window setWindowEventsCallback:receiveWindowEvents];
      [window setOtherRetainedEventsCallback:otherRetainedEventsCallback];
      [window setRenderFrameCallback:renderFrame];
   }
   return( [app run]);
}



